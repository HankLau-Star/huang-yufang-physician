import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(projectRoot, "app");

const sourceText = (
  await Promise.all(
    ["page.tsx", "layout.tsx", "globals.css"].map((file) =>
      readFile(path.join(appDir, file), "utf8"),
    ),
  )
).join("\n");

const allCharacters = new Set(Array.from(sourceText, (character) => character.codePointAt(0)));
const scriptCharacters = new Set(
  Array.from("黄玉芳仁医者醫心济世谨述", (character) => character.codePointAt(0)),
);

function rangeIncludes(rangeText, codePoint) {
  const raw = rangeText.trim().replace(/^U\+/i, "");
  if (raw.includes("?")) {
    const min = Number.parseInt(raw.replaceAll("?", "0"), 16);
    const max = Number.parseInt(raw.replaceAll("?", "f"), 16);
    return codePoint >= min && codePoint <= max;
  }
  const [start, end = start] = raw.split("-");
  return codePoint >= Number.parseInt(start, 16) && codePoint <= Number.parseInt(end, 16);
}

function blockMatches(block, characters) {
  const match = block.match(/unicode-range:\s*([^;]+);/i);
  if (!match) return true;
  const ranges = match[1].split(",");
  return Array.from(characters).some((codePoint) =>
    ranges.some((range) => rangeIncludes(range, codePoint)),
  );
}

async function selectFontFaces({ packagePath, cssFile, characters }) {
  const absolutePackagePath = path.join(projectRoot, "node_modules", ...packagePath.split("/"));
  const css = await readFile(path.join(absolutePackagePath, cssFile), "utf8");
  const blocks = css.match(/@font-face\s*\{[\s\S]*?\n\}/g) ?? [];
  const selected = blocks.filter((block) => blockMatches(block, characters));
  const relativePackagePath = packagePath.replaceAll("\\", "/");

  return selected.map((block) => {
    const woff2 = block.match(/url\((?:"|')?(\.\/files\/[^)'\"]+\.woff2)(?:"|')?\)/i);
    if (!woff2) throw new Error(`Missing WOFF2 source in ${packagePath}/${cssFile}`);
    const format = block.includes("woff2-variations") ? "woff2-variations" : "woff2";
    return block.replace(
      /\s+src:\s*[^;]+;/i,
      `\n  src: url("../node_modules/${relativePackagePath}/${woff2[1].slice(2)}") format("${format}");`,
    );
  });
}

const sections = await Promise.all([
  selectFontFaces({
    packagePath: "@fontsource-variable/noto-sans-sc",
    cssFile: "wght.css",
    characters: allCharacters,
  }),
  selectFontFaces({
    packagePath: "@fontsource-variable/noto-serif-sc",
    cssFile: "wght.css",
    characters: allCharacters,
  }),
  selectFontFaces({
    packagePath: "@fontsource/ma-shan-zheng",
    cssFile: "400.css",
    characters: scriptCharacters,
  }),
]);

const banner = [
  "/* Generated by scripts/build-font-subset.mjs.",
  "   Only glyph ranges used by this site are bundled for fast mainland-mobile delivery. */",
  "",
].join("\n");

await writeFile(
  path.join(appDir, "fonts.local.css"),
  `${banner}${sections.flat().join("\n\n")}\n`,
  "utf8",
);

console.log(`Wrote ${sections.flat().length} local font ranges.`);
